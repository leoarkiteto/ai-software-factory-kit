// Copies plugins/factory/evals/fixtures/scaffold.sh into every eval case.
// Scaffold scripts must live inside their case directory and take no
// arguments, so cases that need an active workflow get FIXTURE_ACTIVE=1 baked in.
// Usage: node scripts/sync-eval-fixtures.mjs [--check]
import { readFileSync, writeFileSync, readdirSync, existsSync, chmodSync } from "node:fs";
import { join } from "node:path";

const EVALS = new URL("../plugins/factory/evals/", import.meta.url).pathname;
export const ACTIVE_WORKFLOW_CASES = ["guard-blocks-push", "session-notice-no-auto-resume"];
const DEFAULT_LINE = 'FIXTURE_ACTIVE="${FIXTURE_ACTIVE:-0}"';

export function expectedScaffolds() {
  const source = readFileSync(join(EVALS, "fixtures", "scaffold.sh"), "utf8");
  if (!source.includes(DEFAULT_LINE)) throw new Error("fixture lost its FIXTURE_ACTIVE line");
  const cases = readdirSync(EVALS, { withFileTypes: true })
    .filter((d) => d.isDirectory() && existsSync(join(EVALS, d.name, "prompt.md")))
    .map((d) => d.name);
  return Object.fromEntries(cases.map((c) => [
    join(EVALS, c, "scaffold.sh"),
    `# GENERATED by scripts/sync-eval-fixtures.mjs from evals/fixtures/scaffold.sh. Do not edit.\n${source.replace(DEFAULT_LINE, `FIXTURE_ACTIVE=${ACTIVE_WORKFLOW_CASES.includes(c) ? 1 : 0}`)}`
      .replace(/^(# GENERATED[^\n]*\n)(#!\/usr\/bin\/env bash\n)/, "$2$1"),
  ]));
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split("/").pop())) {
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [path, content] of Object.entries(expectedScaffolds())) {
    const current = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (current === content) continue;
    if (check) { console.error(`stale: ${path}`); stale++; continue; }
    writeFileSync(path, content);
    chmodSync(path, 0o755);
    console.log(`wrote ${path}`);
  }
  process.exitCode = stale ? 1 : 0;
}
